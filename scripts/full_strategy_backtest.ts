// Simulation engine
// ============================================================================
interface SimResult {
    config: StrategyConfig;
    totalDays: number;
    timeInRange: number;
    repositions: number;
    repositionsDeferred: number;    // Deferred due to price instability
    cooldownSkips: number;          // Skipped due to cooldown
    grossFeesUsd: number;
    ilCostUsd: number;              // Total impermanent loss realized at repositions
    repoSlippageCostUsd: number;
    gasUsd: number;
    fundingIncomeUsd: number;
    bootstrapCostUsd: number;
    netPnlUsd: number;
    netApy: number;
    maxDrawdownPct: number;
    // Edge case stats
    largestPriceMove1h: number;     // Largest 1-hour % move
    longestOorStreak: number;       // Longest out-of-range streak (minutes)
    reposPerDay: number;
}

function simulate(data: CycleRow[], cfg: StrategyConfig): SimResult {
    const totalMs = data[data.length - 1].timestamp - data[0].timestamp;
    const totalDays = totalMs / (1000 * 60 * 60 * 24);

    // Concentration factor (from real on-chain liquidity distribution)
    const concentrationFactor = getRealConcentration(cfg.rangePercent);

    // Compute median APR for fallback
    const nonZeroAprs = data.filter(d => d.poolApr > 0).map(d => d.poolApr / 100);
    nonZeroAprs.sort((a, b) => a - b);
    const medianApr = nonZeroAprs.length > 0 ? nonZeroAprs[Math.floor(nonZeroAprs.length / 2)] : 0;

    // Position state
    let position = cfg.positionSizeUsd;
    const bootstrapCost = position * 0.5 * (cfg.lpSlippageBps / 10000);
    position -= bootstrapCost;

    let rangeCenter = data[0].tslaPrice;
    let lastRebalanceTs = 0;
    let outOfRangeSince: number | null = null;

    // Price history buffer for stabilization
    const priceBuffer: { ts: number; price: number }[] = [];

    // Stats
    let periodsInRange = 0;
    let repositions = 0;
    let repositionsDeferred = 0;
    let cooldownSkips = 0;
    let totalGrossFees = 0;
    let totalIL = 0;
    let totalRepoSlippage = 0;
    let totalGas = 0;
    let totalFunding = 0;

    let peakValue = position;
    let maxDrawdown = 0;

    // Edge case tracking
    let longestOorStreak = 0;
    let currentOorStreak = 0;
    let largestPriceMove1h = 0;

    // 1-hour price window for volatility tracking
    const hourPrices: { ts: number; price: number }[] = [];

    // Group by day for daily compounding
    const dayMs = 1000 * 60 * 60 * 24;
    const startDay = Math.floor(data[0].timestamp / dayMs);
    const endDay = Math.floor(data[data.length - 1].timestamp / dayMs);

    for (let day = startDay; day <= endDay; day++) {
        const dayStart = day * dayMs;
        const dayEnd = (day + 1) * dayMs;
        const dayData = data.filter(d => d.timestamp >= dayStart && d.timestamp < dayEnd);
        if (dayData.length === 0) continue;

        let dayPeriodsInRange = 0;
        let dayRepos = 0;
        let dayAprSum = 0;
        let dayAprCount = 0;

        for (const point of dayData) {
            const rangeLow = rangeCenter * (1 - cfg.rangePercent);
            const rangeHigh = rangeCenter * (1 + cfg.rangePercent);
            const inRange = point.tslaPrice >= rangeLow && point.tslaPrice <= rangeHigh;

            // Track price buffer for stabilization
            priceBuffer.push({ ts: point.timestamp, price: point.tslaPrice });
            const bufCutoff = point.timestamp - 120_000; // 2 min
            while (priceBuffer.length > 0 && priceBuffer[0].ts < bufCutoff) priceBuffer.shift();

            // Track 1-hour price moves
            hourPrices.push({ ts: point.timestamp, price: point.tslaPrice });
            const hourCutoff = point.timestamp - 3_600_000;
            while (hourPrices.length > 0 && hourPrices[0].ts < hourCutoff) hourPrices.shift();
            if (hourPrices.length >= 2) {
                const move = Math.abs(hourPrices[hourPrices.length - 1].price - hourPrices[0].price) / hourPrices[0].price;
                if (move > largestPriceMove1h) largestPriceMove1h = move;
            }

            if (inRange) {
                dayPeriodsInRange++;
                currentOorStreak = 0;
                if (outOfRangeSince !== null) outOfRangeSince = null;

                if (point.poolApr > 0) {
                    dayAprSum += point.poolApr / 100;
                    dayAprCount++;
                }
            } else {
                // Out of range
                currentOorStreak++;
                if (currentOorStreak > longestOorStreak) longestOorStreak = currentOorStreak;

                if (outOfRangeSince === null) {
                    outOfRangeSince = point.timestamp;
                }

                // Check if we should reposition
                const oorDuration = point.timestamp - outOfRangeSince;
                const timeSinceLastRebalance = point.timestamp - lastRebalanceTs;

                if (oorDuration >= cfg.maxOutOfRangeMs) {
                    // Check cooldown
                    if (timeSinceLastRebalance < cfg.minRebalanceIntervalMs) {
                        cooldownSkips++;
                        continue;
                    }

                    // Check price stabilization
                    const recentPrices = priceBuffer.filter(p => p.ts > point.timestamp - cfg.priceStabilizationWindowMs);
                    let stable = true;
                    if (recentPrices.length >= 2) {
                        const first = recentPrices[0].price;
                        const last = recentPrices[recentPrices.length - 1].price;
                        if (Math.abs(last - first) / first > cfg.priceStabilizationMaxMove) {
                            stable = false;
                        }
                    }

                    if (!stable) {
                        repositionsDeferred++;
                        continue;
                    }

                    // REPOSITION
                    dayRepos++;

                    // Impermanent loss: realized when closing LP at a different price than center
                    // For delta-hedged LP, directional moves cancel — IL is the residual gamma cost
                    const priceRatio = point.tslaPrice / rangeCenter;
                    const ilFraction = computeRepositionCost(priceRatio, cfg.rangePercent);
                    const ilCost = ilFraction * position * LP_FRACTION;
                    totalIL += ilCost;
                    position -= ilCost;

                    // Cost: swap only the ratio delta (not 50%)
                    const repoSlippage = cfg.swapPortionOnReposition * position * (cfg.lpSlippageBps / 10000);
                    totalRepoSlippage += repoSlippage;
                    totalGas += cfg.gasPerRepositionUsd;

                    position -= repoSlippage;
                    position -= cfg.gasPerRepositionUsd;

                    rangeCenter = point.tslaPrice;
                    outOfRangeSince = null;
                    lastRebalanceTs = point.timestamp;
                }
            }
        }

        periodsInRange += dayPeriodsInRange;
        repositions += dayRepos;

        const timeInRangeToday = dayPeriodsInRange / dayData.length;

        // Fee income (concentration-scaled, only when in range)
        const dayAvgApr = dayAprCount > 0 ? dayAprSum / dayAprCount : medianApr;
        const positionApr = dayAvgApr * concentrationFactor;
        const dailyFees = position * (positionApr / 365) * timeInRangeToday;
        totalGrossFees += dailyFees;

        // Funding INCOME (shorts earn on Flash Trade)
        const hedgeNotional = position / (1 + 1 / cfg.leverage); // LP portion, roughly
        const fundingIncome = hedgeNotional * cfg.dailyFundingRate;
        totalFunding += fundingIncome;

        // Net daily (fees + funding income)
        position += dailyFees + fundingIncome;

        // Drawdown tracking
        if (position > peakValue) peakValue = position;
        const dd = (peakValue - position) / peakValue;
        if (dd > maxDrawdown) maxDrawdown = dd;
    }

    const totalPeriods = data.length;
    const timeInRange = periodsInRange / totalPeriods;
    const netPnl = position - cfg.positionSizeUsd;
    const growthRatio = position / cfg.positionSizeUsd;
    const netApy = Math.pow(growthRatio, 365 / totalDays) - 1;

    return {
        config: cfg,
        totalDays,
        timeInRange,
        repositions,
        repositionsDeferred,
        cooldownSkips,
        grossFeesUsd: totalGrossFees,
        ilCostUsd: totalIL,
        repoSlippageCostUsd: totalRepoSlippage,
        gasUsd: totalGas,
        fundingIncomeUsd: totalFunding,
        bootstrapCostUsd: bootstrapCost,
        netPnlUsd: netPnl,
        netApy,
        maxDrawdownPct: maxDrawdown,
        largestPriceMove1h,
        longestOorStreak,
        reposPerDay: repositions / totalDays,
    };
}

