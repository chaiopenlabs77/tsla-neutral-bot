interface CycleRow {
    timestamp: number;
    tslaPrice: number;
    poolApr: number;
    poolTvl: number;
}

function loadData(): CycleRow[] {
    // Try full export first, then fallback to old format
    for (const csvPath of ['/tmp/vm_cycles_full.csv', '/tmp/vm_cycles.csv']) {
        if (!fs.existsSync(csvPath)) continue;
        const lines = fs.readFileSync(csvPath, 'utf-8').split('\n').filter(Boolean);
        const header = lines[0].split(',');
        const priceIdx = header.indexOf('tsla_price');
        const aprIdx = header.indexOf('pool_apr');
        const tvlIdx = header.indexOf('pool_tvl');
        const tsIdx = header.indexOf('timestamp');

        const rows: CycleRow[] = [];
        for (let i = 1; i < lines.length; i++) {
            const cols = lines[i].split(',');
            const tslaPrice = parseFloat(cols[priceIdx >= 0 ? priceIdx : 1]);
            const poolApr = parseFloat(cols[aprIdx >= 0 ? aprIdx : 6]);
            const poolTvl = parseFloat(cols[tvlIdx >= 0 ? tvlIdx : 7]);
            if (tslaPrice > 0) {
                rows.push({
                    timestamp: parseInt(cols[tsIdx >= 0 ? tsIdx : 0]),
                    tslaPrice,
                    poolApr: isNaN(poolApr) ? 0 : poolApr,
                    poolTvl: isNaN(poolTvl) ? 0 : poolTvl,
                });
            }
        }
        console.log(`Loaded ${rows.length} rows from ${csvPath}`);
        return rows;
    }
    console.error('ERROR: No CSV data found. Export from VM first.');
    process.exit(1);
}

